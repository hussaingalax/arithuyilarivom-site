// =========================================================
// LANGUAGE STATE
// =========================================================

let currentLang =
  localStorage.getItem('aa_meditation_lang') || 'en';


// =========================================================
// TRANSLATION FUNCTION
// =========================================================

function t(key) {

  return (
    I18N[currentLang]?.[key] ||
    I18N.en[key] ||
    key
  );

}


// =========================================================
// APPLY LANGUAGE
// =========================================================

function setLang(lang) {

  currentLang =
    lang === 'ta' ? 'ta' : 'en';

  localStorage.setItem(
    'aa_meditation_lang',
    currentLang
  );

  document.documentElement.lang =
    currentLang === 'ta'
      ? 'ta'
      : 'en';

  // Text content
  document
    .querySelectorAll('[data-i18n]')
    .forEach(el => {

      el.textContent =
        t(el.dataset.i18n);

    });

  // Placeholder translation
  document
    .querySelectorAll('[data-i18n-placeholder]')
    .forEach(el => {

      el.placeholder =
        t(el.dataset.i18nPlaceholder);

    });

  // Language button state
  document
    .querySelectorAll('[data-lang]')
    .forEach(button => {

      button.classList.toggle(
        'active',
        button.dataset.lang === currentLang
      );

    });

  // Re-render dynamic content
  if (
    typeof window.renderDynamic === 'function'
  ) {
    window.renderDynamic();
  }

  // Page-specific dynamic renderers
  if (
    typeof window.renderOffers === 'function'
  ) {
    window.renderOffers();
  }

}


// =========================================================
// LANGUAGE BUTTON CLICK
// =========================================================

document.addEventListener(
  'click',
  event => {

    const button =
      event.target.closest('[data-lang]');

    if (!button) return;

    setLang(button.dataset.lang);

  }
);
